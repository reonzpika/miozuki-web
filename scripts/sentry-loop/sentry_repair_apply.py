"""Deterministic apply / reject for an approved Sentry auto-fix.

Ported from cursor/LinkedIn/scripts/grow_repair_apply.py. The Remote Control
approval session calls this instead of running git/gh itself, so the irreversible
step (push the branch + open a draft PR) is deterministic and auditable, not left
to the model. Reads the repair branch and base from repair_state.json, which must
be in AWAITING_APPROVAL.

    python scripts/sentry-loop/sentry_repair_apply.py apply    # push branch, open draft PR
    python scripts/sentry-loop/sentry_repair_apply.py reject   # discard the branch

Stage-1 ceiling: this pushes a NON-master branch and opens a DRAFT PR. It never
merges and never touches master; Ryo merges the PR himself.

Exit codes:
  0 - applied or rejected cleanly
  1 - nothing to do / unsafe state (no branch, dirty tree, wrong status)
  2 - a git/gh step failed
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
REPO_ROOT = ROOT.parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import repair_state  # noqa: E402


def _git(*args: str, check: bool = True) -> str:
    res = subprocess.run(
        ["git", *args], cwd=str(REPO_ROOT), capture_output=True, text=True, encoding="utf-8"
    )
    if check and res.returncode != 0:
        raise RuntimeError(f"git {' '.join(args)} failed: {res.stderr.strip()[:300]}")
    return res.stdout.strip()


def _schedule_self_reap(pid) -> None:
    """The Remote Control approval session that calls us does not self-exit after
    acting, so schedule it to close ~15s from now (enough to send its final
    reply). Best-effort, Windows-only; a no-op elsewhere or if pid is unknown."""
    if not pid or sys.platform != "win32":
        return
    try:
        subprocess.Popen(
            ["cmd", "/c", f"timeout /t 15 /nobreak >nul & taskkill /PID {pid} /T /F"],
            creationflags=subprocess.DETACHED_PROCESS | subprocess.CREATE_NO_WINDOW,
        )
        print(f"[apply] scheduled approval session pid={pid} to close in ~15s")
    except Exception as e:
        print(f"[apply] could not schedule session reap: {e}", file=sys.stderr)


def apply_fix() -> int:
    state = repair_state.read_state()
    if state.get("status") != repair_state.AWAITING_APPROVAL:
        print(f"[apply] nothing awaiting approval (status={state.get('status')})")
        return 1
    branch = state.get("branch")
    base = state.get("base_branch") or "master"
    issue_id = state.get("issue_id", "")
    proposal = state.get("proposal") or {}
    if not branch:
        print("[apply] no repair branch recorded in state")
        return 1

    try:
        if _git("status", "--porcelain", "--untracked-files=no", check=False).strip():
            print("[apply] base tree has uncommitted changes; aborting to avoid clobber")
            return 1
        # Push the repair branch only (never master).
        _git("push", "-u", "origin", branch)
        pr_url = _open_draft_pr(branch, base, issue_id, proposal)
    except Exception as e:
        repair_state.set_status(repair_state.FAILED, reason=f"apply failed: {e}")
        print(f"[apply] FAILED: {e}", file=sys.stderr)
        return 2

    # The loop has done its part (fix proposed + Ryo-approved -> PR open). Ledger
    # the issue DONE so it is never re-fixed; Ryo merges the PR himself.
    repair_state.accept(issue_id)
    print(f"[apply] pushed {branch}; draft PR: {pr_url or '(no url returned)'}")
    _schedule_self_reap(state.get("approval_pid"))
    return 0


def _open_draft_pr(branch: str, base: str, issue_id: str, proposal: dict) -> str:
    title = f"Sentry auto-fix: {issue_id}"
    body = (
        f"Automated proposed fix for Sentry issue `{issue_id}` (Ryo-approved on phone).\n\n"
        f"**Root cause:** {proposal.get('root_cause', '')}\n\n"
        f"**Change:** {proposal.get('diff_summary', '')}\n\n"
        f"Notes: {proposal.get('notes', '')}\n\n"
        "Generated by the sentry-loop (Stage 1, propose-only). Review before merging."
    )
    res = subprocess.run(
        ["gh", "pr", "create", "--draft", "--base", base, "--head", branch,
         "--title", title, "--body", body],
        cwd=str(REPO_ROOT), capture_output=True, text=True, encoding="utf-8",
    )
    if res.returncode != 0:
        print(f"[apply] gh pr create failed: {res.stderr[:300]}", file=sys.stderr)
        return ""
    return res.stdout.strip()


def reject_fix() -> int:
    state = repair_state.read_state()
    branch = state.get("branch")
    base = state.get("base_branch") or "master"
    issue_id = state.get("issue_id", "")
    if branch:
        try:
            current = _git("rev-parse", "--abbrev-ref", "HEAD")
            if current == branch:
                _git("checkout", base, check=False)
            _git("branch", "-D", branch, check=False)
        except Exception as e:
            print(f"[apply] reject cleanup warning: {e}", file=sys.stderr)
    pid = state.get("approval_pid")
    repair_state.reject(issue_id)
    print("[apply] fix rejected; branch discarded, issue ledgered REJECTED.")
    _schedule_self_reap(pid)
    return 0


def main(argv: list[str]) -> int:
    action = argv[1] if len(argv) > 1 else ""
    if action == "apply":
        return apply_fix()
    if action == "reject":
        return reject_fix()
    print("usage: sentry_repair_apply.py [apply|reject]", file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
