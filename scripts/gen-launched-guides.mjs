// Generates lib/launched-guides.json: which guide-hub pages are "launched"
// (eligible for the sitemap) vs "pending" (still carrying VERIFY markers).
//
// The rule: a guide enters the sitemap only when its source contains zero
// VERIFY markers. Markers ({/* VERIFY: ... */} in prose, /* VERIFY: ... */ in
// FAQ object literals) are invisible on the rendered page and flag content
// Ting hasn't confirmed yet. So "Ting resolved every marker and published"
// IS the launch action; no separate manual sitemap step exists.
//
// Runs as part of `prebuild` (before every `next build`), so the JSON is
// always regenerated from the actual .mdx sources at build time. The JSON is
// committed so `next dev` (which skips prebuild) still has a current copy;
// the standing publish procedure always runs a build before committing, which
// keeps it in sync.

import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const HUBS = ['moissanite-guide', 'pearl-guide', 'bridal-guide'];

const launched = [];
const pending = [];

for (const hub of HUBS) {
  const hubDir = join(ROOT, 'app', hub);
  if (!existsSync(hubDir)) continue;

  const candidates = [];
  const pillar = join(hubDir, 'page.mdx');
  if (existsSync(pillar)) candidates.push({ route: `/${hub}`, file: pillar });

  for (const entry of readdirSync(hubDir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const page = join(hubDir, entry.name, 'page.mdx');
    if (existsSync(page)) candidates.push({ route: `/${hub}/${entry.name}`, file: page });
  }

  for (const c of candidates) {
    const src = readFileSync(c.file, 'utf8');
    (src.includes('VERIFY:') ? pending : launched).push(c.route);
  }
}

launched.sort();
pending.sort();

const outPath = join(ROOT, 'lib', 'launched-guides.json');
writeFileSync(
  outPath,
  JSON.stringify(
    {
      note: 'Generated by scripts/gen-launched-guides.mjs during prebuild. Do not edit by hand.',
      launched,
      pending,
    },
    null,
    2,
  ) + '\n',
);

console.log(
  `[launched-guides] ${launched.length} launched, ${pending.length} pending (VERIFY markers present)`,
);
